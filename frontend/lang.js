function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  localStorage.setItem('vishnudatta_lang', lang);

  // Update button classes
  const btnEn = document.getElementById('btn-lang-en');
  const btnTe = document.getElementById('btn-lang-te');
  if (btnEn && btnTe) {
    if (lang === 'te') {
      btnTe.classList.add('active');
      btnEn.classList.remove('active');
      document.body.classList.add('lang-telugu');
    } else {
      btnEn.classList.add('active');
      btnTe.classList.remove('active');
      document.body.classList.remove('lang-telugu');
    }
  }

  // Header & Contact
  const elHeaderName = document.getElementById('header-company-name');
  if (elHeaderName) elHeaderName.textContent = dict.companyName;

  const elContactUsLabel = document.getElementById('text-contact-us-label');
  if (elContactUsLabel) elContactUsLabel.textContent = dict.contactUs;

  // Left Merchant Info
  const elMerchantTitle = document.getElementById('text-merchant-title');
  if (elMerchantTitle) elMerchantTitle.textContent = dict.merchantTitle;

  const elMerchantSubtitle = document.getElementById('text-merchant-subtitle');
  if (elMerchantSubtitle) elMerchantSubtitle.textContent = dict.merchantSubtitle;

  const elLabelAddress = document.getElementById('label-address');
  if (elLabelAddress) elLabelAddress.textContent = dict.labelAddress;

  const elMerchantAddress = document.getElementById('text-merchant-address');
  if (elMerchantAddress) elMerchantAddress.textContent = dict.merchantAddress;

  const elLabelProprietor = document.getElementById('label-proprietor');
  if (elLabelProprietor) elLabelProprietor.textContent = dict.labelProprietor;

  const elMerchantProprietor = document.getElementById('text-merchant-proprietor');
  if (elMerchantProprietor) elMerchantProprietor.textContent = dict.merchantProprietor;

  // Login Form elements (if on index.html)
  const elLoginHeading = document.getElementById('text-login-heading');
  if (elLoginHeading) elLoginHeading.textContent = dict.loginHeading;

  const elLabelLoginUser = document.getElementById('label-login-username');
  if (elLabelLoginUser) elLabelLoginUser.textContent = dict.labelLoginUsername;
  const inputLoginUser = document.getElementById('login-username');
  if (inputLoginUser) inputLoginUser.placeholder = dict.placeholderLoginUsername;

  const elLabelLoginPass = document.getElementById('label-login-password');
  if (elLabelLoginPass) elLabelLoginPass.textContent = dict.labelLoginPassword;
  const inputLoginPass = document.getElementById('login-password');
  if (inputLoginPass) inputLoginPass.placeholder = dict.placeholderLoginPassword;

  const elBtnLogin = document.getElementById('text-btn-login');
  if (elBtnLogin) elBtnLogin.textContent = dict.btnLogin;

  const elTextNoAccount = document.getElementById('text-no-account');
  if (elTextNoAccount) elTextNoAccount.textContent = dict.textNoAccount;

  const elLinkRegister = document.getElementById('link-redirect-register');
  if (elLinkRegister) elLinkRegister.textContent = dict.linkRegister;

  // Registration Form elements (if on register.html)
  const elRegisterHeading = document.getElementById('text-register-heading');
  if (elRegisterHeading) elRegisterHeading.textContent = dict.registerHeading;

  const elLabelRegFullname = document.getElementById('label-reg-fullname');
  if (elLabelRegFullname) elLabelRegFullname.textContent = dict.labelRegFullname;
  const inputRegFullname = document.getElementById('reg-fullname');
  if (inputRegFullname) inputRegFullname.placeholder = dict.placeholderRegFullname;

  const elLabelRegPhone = document.getElementById('label-reg-phone');
  if (elLabelRegPhone) elLabelRegPhone.textContent = dict.labelRegPhone;
  const inputRegPhone = document.getElementById('reg-phone');
  if (inputRegPhone) inputRegPhone.placeholder = dict.placeholderRegPhone;

  const elLabelRegUsername = document.getElementById('label-reg-username');
  if (elLabelRegUsername) elLabelRegUsername.textContent = dict.labelRegUsername;
  const inputRegUsername = document.getElementById('reg-username');
  if (inputRegUsername) inputRegUsername.placeholder = dict.placeholderRegUsername;

  const elLabelRegPassword = document.getElementById('label-reg-password');
  if (elLabelRegPassword) elLabelRegPassword.textContent = dict.labelRegPassword;
  const inputRegPassword = document.getElementById('reg-password');
  if (inputRegPassword) inputRegPassword.placeholder = dict.placeholderRegPassword;

  const elLabelRegConfirmpass = document.getElementById('label-reg-confirmpass');
  if (elLabelRegConfirmpass) elLabelRegConfirmpass.textContent = dict.labelRegConfirmpass;
  const inputRegConfirmpass = document.getElementById('reg-confirm-password');
  if (inputRegConfirmpass) inputRegConfirmpass.placeholder = dict.placeholderRegConfirmpass;

  const elLabelRegCaptcha = document.getElementById('label-reg-captcha');
  if (elLabelRegCaptcha) elLabelRegCaptcha.textContent = dict.labelCaptcha;
  const inputRegCaptcha = document.getElementById('reg-captcha-input');
  if (inputRegCaptcha) inputRegCaptcha.placeholder = dict.placeholderCaptcha;

  const elBtnRegister = document.getElementById('text-btn-register');
  if (elBtnRegister) elBtnRegister.textContent = dict.btnRegister;

  const elTextAlreadyAccount = document.getElementById('text-already-account');
  if (elTextAlreadyAccount) elTextAlreadyAccount.textContent = dict.textAlreadyAccount;

  const elLinkLogin = document.getElementById('link-redirect-login');
  if (elLinkLogin) elLinkLogin.textContent = dict.linkLogin;

  // Dashboard elements
  const elDashBrandTitle = document.getElementById('dash-brand-title');
  if (elDashBrandTitle) elDashBrandTitle.textContent = dict.dashBrandTitle;

  const elTabExisting = document.getElementById('text-tab-existing');
  if (elTabExisting) elTabExisting.textContent = dict.tabExisting;

  const elTabExistingSub = document.getElementById('text-tab-existing-sub');
  if (elTabExistingSub) elTabExistingSub.textContent = dict.tabExistingSub;

  const elTabCreate = document.getElementById('text-tab-create');
  if (elTabCreate) elTabCreate.textContent = dict.tabCreate;

  const elTabCreateSub = document.getElementById('text-tab-create-sub');
  if (elTabCreateSub) elTabCreateSub.textContent = dict.tabCreateSub;

  const elMetricTotalBills = document.getElementById('text-metric-total-bills');
  if (elMetricTotalBills) elMetricTotalBills.textContent = dict.metricTotalBills;

  const elMetricTotalQty = document.getElementById('text-metric-total-qty');
  if (elMetricTotalQty) elMetricTotalQty.textContent = dict.metricTotalQty;

  const elMetricTotalAmount = document.getElementById('text-metric-total-amount');
  if (elMetricTotalAmount) elMetricTotalAmount.textContent = dict.metricTotalAmount;

  const elBtnExport = document.getElementById('text-btn-export');
  if (elBtnExport) elBtnExport.textContent = dict.btnExport;

  const elBtnImport = document.getElementById('text-btn-import');
  if (elBtnImport) elBtnImport.textContent = dict.btnImport;

  const elTitleExisting = document.getElementById('title-existing-bills');
  if (elTitleExisting) elTitleExisting.textContent = dict.titleExisting;

  const elDescExisting = document.getElementById('desc-existing-bills');
  if (elDescExisting) elDescExisting.textContent = dict.descExisting;

  const elTitleCreateForm = document.getElementById('title-create-bill-form');
  if (elTitleCreateForm) elTitleCreateForm.textContent = dict.titleCreateForm;

  const elBtnSaveBill = document.getElementById('text-btn-save-bill');
  if (elBtnSaveBill) elBtnSaveBill.textContent = dict.btnSaveBill;

  const elTextLogout = document.getElementById('text-logout');
  if (elTextLogout) elTextLogout.textContent = dict.textLogout;

  // Footer
  const elFooterText = document.getElementById('footer-text');
  if (elFooterText) elFooterText.innerHTML = dict.footerText;

  const elFooterPropLabel = document.getElementById('footer-prop-label');
  if (elFooterPropLabel) elFooterPropLabel.textContent = dict.footerPropLabel;

  const elFooterPropName = document.getElementById('footer-prop-name');
  if (elFooterPropName) elFooterPropName.textContent = dict.footerPropName;
}

// Global initialization for languages
document.addEventListener('DOMContentLoaded', () => {
  const currentLang = localStorage.getItem('vishnudatta_lang') || 'en';
  applyLanguage(currentLang);

  const btnEn = document.getElementById('btn-lang-en');
  const btnTe = document.getElementById('btn-lang-te');

  if (btnEn) {
    btnEn.addEventListener('click', () => applyLanguage('en'));
  }
  if (btnTe) {
    btnTe.addEventListener('click', () => applyLanguage('te'));
  }
});
